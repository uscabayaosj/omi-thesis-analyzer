import CoreText
import Foundation
import SwiftUI
import UIKit

/// Exports only saved content; never requests another transcription or summary.
struct ConversationTextExport: Sendable {
    enum Content: String, CaseIterable { case summary, transcript }
    enum Format: String, CaseIterable { case pdf = "PDF", txt = "TXT" }
    struct Block: Sendable {
        enum Style: Sendable { case title, metadata, heading, body, timestamp }
        let text: String
        let style: Style
    }
    let title: String
    let content: Content
    let blocks: [Block]

    static func available(_ content: Content, in conversation: NativeConversation) -> Bool {
        switch content {
        case .summary:
            return !(conversation.structured?.overview?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ?? true)
                || conversation.structured?.actionItems?.isEmpty == false
        case .transcript:
            return conversation.transcriptSegments?.contains { !$0.text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty } == true
        }
    }

    init(conversation: NativeConversation, content: Content) {
        self.title = conversation.displayTitle
        self.content = content
        var result = [Block(text: "\(conversation.displayTitle) - \(content == .summary ? "Summary" : "Transcriptions")", style: .title)]
        if let date = conversation.displayDate {
            let formatter = DateFormatter()
            formatter.locale = Locale(identifier: "en_GB")
            formatter.dateFormat = "HH:mm yyyy/MM/dd z"
            result.append(Block(text: formatter.string(from: date), style: .metadata))
        }
        if let pin = conversation.geolocation, pin.valid {
            result.append(Block(text: pin.label, style: .metadata))
        }
        result.append(Block(text: "\(content == .summary ? "Generated by AI" : "Automatically transcribed"). Please verify before use.", style: .metadata))
        if conversation.source == "trace-recovered" {
            result.append(Block(text: "Recovered recording: date and time are approximate; this may be part of a longer conversation.", style: .metadata))
        }
        switch content {
        case .summary:
            if let overview = conversation.structured?.overview, !overview.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                result.append(Block(text: "Overview", style: .heading))
                result.append(Block(text: overview, style: .body))
            }
            if let items = conversation.structured?.actionItems, !items.isEmpty {
                result.append(Block(text: "Next steps", style: .heading))
                for item in items {
                    var text = "• \(item.description)"
                    if item.completed == true { text += "\n  Completed" }
                    if let due = item.dueDateLabel { text += "\n  Due: \(due)" }
                    result.append(Block(text: text, style: .body))
                }
            }
        case .transcript:
            for segment in conversation.transcriptSegments ?? [] where !segment.text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                if let start = segment.start, start.isFinite, start >= 0 {
                    let seconds = Int(min(start, Double(Int.max / 2)))
                    result.append(Block(text: String(format: "[%02d:%02d:%02d]", seconds / 3600, (seconds % 3600) / 60, seconds % 60), style: .timestamp))
                }
                // Match the readable transcript: do not export tentative identities as facts.
                let name = segment.speakerConfirmed == true ? segment.speakerName?.trimmingCharacters(in: .whitespacesAndNewlines) : nil
                result.append(Block(text: (name?.isEmpty == false ? "\(name!): " : "") + segment.text, style: .body))
            }
        }
        blocks = result
    }

    func write(format: Format) throws -> URL {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent("TRACE-exports", isDirectory: true)
            .appendingPathComponent(UUID().uuidString, isDirectory: true)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        let forbidden = CharacterSet.controlCharacters.union(CharacterSet(charactersIn: "/\\:*?\"<>|"))
        let safeTitle = title.components(separatedBy: forbidden).joined(separator: " ").trimmingCharacters(in: .whitespacesAndNewlines)
        let filename = String((safeTitle.isEmpty ? "Conversation" : safeTitle).prefix(120))
            + (content == .summary ? "_summary" : "_transcription") + "." + format.rawValue.lowercased()
        let url = directory.appendingPathComponent(filename)
        do {
            switch format {
            case .txt:
                var text = ""
                for block in blocks {
                    switch block.style {
                    case .metadata: text += block.text + "\n"
                    case .title: text += block.text + "\n"
                    case .heading: text += "\n" + block.text + "\n" + String(repeating: "-", count: block.text.count) + "\n"
                    case .timestamp: text += "\n" + block.text + "\n"
                    case .body: text += block.text + "\n\n"
                    }
                }
                try text.write(to: url, atomically: true, encoding: .utf8)
            case .pdf:
                try pdfData().write(to: url, options: .atomic)
            }
            return url
        } catch {
            try? FileManager.default.removeItem(at: directory)
            throw error
        }
    }

    private func pdfData() throws -> Data {
        let document = NSMutableAttributedString()
        for block in blocks {
            let paragraph = NSMutableParagraphStyle()
            paragraph.lineSpacing = 3
            paragraph.paragraphSpacing = block.style == .metadata ? 2 : 12
            paragraph.paragraphSpacingBefore = block.style == .heading ? 12 : 0
            let size: CGFloat
            let weight: UIFont.Weight
            let color: UIColor
            switch block.style {
            case .title: size = 18; weight = .medium; color = .black
            case .heading: size = 17; weight = .medium; color = .black
            case .metadata, .timestamp: size = 10; weight = .regular; color = .darkGray
            case .body: size = 12; weight = .regular; color = .darkGray
            }
            document.append(NSAttributedString(string: block.text + "\n", attributes: [
                .font: UIFont.systemFont(ofSize: size, weight: weight), .foregroundColor: color, .paragraphStyle: paragraph
            ]))
        }
        let framesetter = CTFramesetterCreateWithAttributedString(document)
        let page = CGRect(x: 0, y: 0, width: 595.28, height: 841.89)
        let body = CGRect(x: 32, y: 64, width: page.width - 64, height: page.height - 140)
        let format = UIGraphicsPDFRendererFormat()
        format.documentInfo = [kCGPDFContextTitle as String: title, kCGPDFContextCreator as String: "TRACE"]
        var paginationFailed = false
        let data = UIGraphicsPDFRenderer(bounds: page, format: format).pdfData { renderer in
            var offset = 0
            var pageNumber = 0
            while offset < document.length {
                renderer.beginPage()
                pageNumber += 1
                let context = renderer.cgContext
                context.setFillColor(UIColor(white: 0.96, alpha: 1).cgColor)
                context.fill(CGRect(x: 0, y: 0, width: page.width, height: 44))
                ("TRACE" as NSString).draw(at: CGPoint(x: 32, y: 15), withAttributes: [.font: UIFont.systemFont(ofSize: 11, weight: .semibold), .foregroundColor: UIColor.darkGray])
                context.saveGState()
                context.textMatrix = .identity
                context.translateBy(x: 0, y: page.height)
                context.scaleBy(x: 1, y: -1)
                let frame = CTFramesetterCreateFrame(framesetter, CFRange(location: offset, length: 0), CGPath(rect: body, transform: nil), nil)
                let visible = CTFrameGetVisibleStringRange(frame)
                guard visible.length > 0 else { paginationFailed = true; context.restoreGState(); break }
                CTFrameDraw(frame, context)
                context.restoreGState()
                offset += visible.length
                let footer = NSMutableParagraphStyle(); footer.lineBreakMode = .byTruncatingTail
                (title as NSString).draw(in: CGRect(x: 32, y: page.height - 38, width: page.width - 104, height: 20), withAttributes: [.font: UIFont.systemFont(ofSize: 9), .foregroundColor: UIColor.gray, .paragraphStyle: footer])
                (String(format: "%02d", pageNumber) as NSString).draw(at: CGPoint(x: page.width - 50, y: page.height - 38), withAttributes: [.font: UIFont.systemFont(ofSize: 9), .foregroundColor: UIColor.gray])
            }
        }
        if paginationFailed { throw CocoaError(.fileWriteUnknown) }
        return data
    }
}

struct ConversationExportFile: Identifiable {
    let id = UUID()
    let url: URL
}

struct ConversationExportShareSheet: UIViewControllerRepresentable {
    let file: ConversationExportFile
    func makeUIViewController(context: Context) -> UIActivityViewController {
        UIActivityViewController(activityItems: [file.url], applicationActivities: nil)
    }
    func updateUIViewController(_ controller: UIActivityViewController, context: Context) {}
}
