#!/usr/bin/env python3
"""Rebuild the six wordless event clips using only the Python standard library."""
from pathlib import Path
import hashlib
import json
import math
import struct

ROOT = Path(__file__).resolve().parent
RATE = 8000
PEAK = 32767  # User-selected 100% digital peak; not calibrated acoustic volume.
PATTERNS = [
    ("Connected", [660, 990], 70, 30, "two rising notes"),
    ("Disconnected", [990, 660], 70, 30, "two falling notes"),
    ("Recording started", [1100, 1100], 80, 55, "two high beeps"),
    ("Paused", [440], 180, 0, "one low beep"),
    ("Low battery", [330, 330, 330], 75, 65, "three low beeps"),
    ("Conversation summary completed", [523, 659, 784], 65, 25, "three rising notes"),
]


def render(frequencies, note_ms, gap_ms):
    samples = []
    frames = RATE * note_ms // 1000
    ramp = RATE * 8 // 1000
    for index, frequency in enumerate(frequencies):
        if index:
            samples.extend([0] * (RATE * gap_ms // 1000))
        for n in range(frames):
            # Eight-millisecond attack/release avoids hard-switch clicks.
            envelope = min(1, n / ramp, (frames - 1 - n) / ramp)
            samples.append(math.sin(2 * math.pi * frequency * n / RATE) * envelope)
    scale = PEAK / max(abs(v) for v in samples)
    return b"".join(struct.pack("<h", round(v * scale)) for v in samples)


def generate():
    parts = ["/* Generated by generate_tones.py: wordless 8 kHz mono s16le; peak 32767. */"]
    manifest = []
    for i, (name, frequencies, note_ms, gap_ms, description) in enumerate(PATTERNS, 1):
        data = render(frequencies, note_ms, gap_ms)
        parts.append(f"static const uint8_t prompt_pcm_{i}[] = {{\n" + "\n".join(
            ",".join(str(v) for v in data[n:n+24]) + "," for n in range(0, len(data), 24)) + "\n};")
        manifest.append(dict(id=i, event=name, pattern=description, frequenciesHz=frequencies,
                             noteMs=note_ms, gapMs=gap_ms, durationMs=len(data)*1000//(RATE*2),
                             sampleRate=RATE, peak=PEAK, sha256=hashlib.sha256(data).hexdigest()))
    parts.append("struct prompt_clip {const uint8_t *pcm; size_t bytes; const char *name;};\n"
                 "static const struct prompt_clip prompt_clips[] = {\n{0},\n" + "".join(
                     f'{{prompt_pcm_{i},sizeof(prompt_pcm_{i}),"{row[0]}"}},\n'
                     for i, row in enumerate(PATTERNS, 1)) + "};")
    (ROOT / "src/trace_prompt_audio.h").write_text("\n".join(parts) + "\n")
    (ROOT / "tone-patterns.json").write_text(json.dumps(manifest, indent=2) + "\n")


if __name__ == "__main__":
    generate()
