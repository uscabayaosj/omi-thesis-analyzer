"use client";

import { useEffect, useState, useCallback, Suspense } from "react";
import { useSearchParams } from "next/navigation";
import Link from "next/link";

interface ConvoRef {
  id: string;
  title: string;
  date: string;
  emoji: string;
}

interface GroupAnalysis {
  cross_conversation_themes: string;
  contradictions_and_tensions: string;
  evolution_and_patterns: string;
  synthesis: string;
  forward_thinking: string;
}

interface StoredGroupAnalysis {
  id: string;
  conversationIds: string[];
  conversations: ConvoRef[];
  timestamp: string;
  analysis: GroupAnalysis;
  custom?: { prompt: string; result: string; timestamp: string };
}

const STORAGE_KEY = "omi-thesis-group-analyses";

function getStoredGroupAnalyses(): StoredGroupAnalysis[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    return raw ? JSON.parse(raw) : [];
  } catch {
    return [];
  }
}

function saveGroupAnalysis(data: Omit<StoredGroupAnalysis, "id" | "timestamp">): StoredGroupAnalysis {
  const all = getStoredGroupAnalyses();
  const id = data.conversationIds.sort().join(",");
  const existing = all.findIndex((a) => a.conversationIds.sort().join(",") === id);

  const stored: StoredGroupAnalysis = {
    ...data,
    id: crypto.randomUUID(),
    timestamp: new Date().toISOString(),
  };

  if (existing >= 0) {
    if (!stored.custom && all[existing].custom) stored.custom = all[existing].custom;
    stored.id = all[existing].id;
    all[existing] = stored;
  } else {
    all.unshift(stored);
  }

  localStorage.setItem(STORAGE_KEY, JSON.stringify(all));
  return stored;
}

function saveGroupCustom(
  conversationIds: string[],
  custom: { prompt: string; result: string }
) {
  const all = getStoredGroupAnalyses();
  const key = conversationIds.sort().join(",");
  const existing = all.find((a) => a.conversationIds.sort().join(",") === key);
  if (existing) {
    existing.custom = { ...custom, timestamp: new Date().toISOString() };
    localStorage.setItem(STORAGE_KEY, JSON.stringify(all));
  }
}

function exportGroupToObsidian(stored: StoredGroupAnalysis): string {
  const dates = stored.conversations.map((c) => c.date.split("T")[0]);
  const dateRange = dates.length > 1 ? `${dates[0]} to ${dates[dates.length - 1]}` : dates[0];
  const titles = stored.conversations.map((c) => c.title).join(", ");
  const safeName = titles.replace(/[\/\\:*?"<>|]/g, "-").substring(0, 80);

  const convoLinks = stored.conversations
    .map((c) => {
      const d = c.date.split("T")[0];
      return `- [[${d} - ${c.title.replace(/[\/\\:*?"<>|]/g, "-")}]]`;
    })
    .join("\n");

  const md = `---
title: "Group Analysis: ${titles.replace(/"/g, '\\"').substring(0, 100)}"
date: ${dateRange}
analyzed: ${stored.timestamp}
type: group-analysis
source: Omi DK2
tags:
  - omi-analysis
  - fieldwork
  - group-analysis
---

# Group Analysis

> [!info] ${stored.conversations.length} conversations analyzed together on ${new Date(stored.timestamp).toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" })}.

## Conversations in this group

${convoLinks}

## 🔗 Cross-Conversation Themes

${stored.analysis.cross_conversation_themes}

## ⚡ Contradictions & Tensions

${stored.analysis.contradictions_and_tensions}

## 📈 Evolution & Patterns

${stored.analysis.evolution_and_patterns}

## 🧩 Synthesis

${stored.analysis.synthesis}

## 🚀 Forward Thinking

${stored.analysis.forward_thinking}
${stored.custom ? `
## ⚙️ Custom Analysis

> **Prompt:** ${stored.custom.prompt}

${stored.custom.result}` : ""}
---
*Generated by [[Omi Thesis Analyzer]] — Pioneer Sovereignty fieldwork analysis.*
`;

  const params = new URLSearchParams({
    vault: "PhDVault",
    name: `Fieldwork/Omi Analysis/Group - ${safeName}`,
    content: md,
    append: "false",
  });

  return `obsidian://advanced-uri?${params.toString()}`;
}

function GroupAnalysisContent() {
  const searchParams = useSearchParams();
  const ids = searchParams.get("ids")?.split(",") || [];

  const [analysis, setAnalysis] = useState<GroupAnalysis | null>(null);
  const [conversations, setConversations] = useState<ConvoRef[]>([]);
  const [loading, setLoading] = useState(true);
  const [analyzing, setAnalyzing] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [customPrompt, setCustomPrompt] = useState("");
  const [showCustom, setShowCustom] = useState(false);
  const [customAnalyzing, setCustomAnalyzing] = useState(false);
  const [exported, setExported] = useState(false);

  // Check for stored analysis
  useEffect(() => {
    const stored = getStoredGroupAnalyses();
    const key = [...ids].sort().join(",");
    const existing = stored.find((a) => [...a.conversationIds].sort().join(",") === key);
    if (existing) {
      setAnalysis(existing.analysis);
      setConversations(existing.conversations);
      if (existing.custom) setCustomPrompt(existing.custom.prompt);
      setLoading(false);
    } else {
      setLoading(false);
    }
  }, [ids]);

  const runAnalysis = useCallback(async () => {
    setAnalyzing(true);
    setError(null);
    try {
      const res = await fetch("/api/analyze-group", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ conversationIds: ids }),
      });
      const data = await res.json();
      if (data.error) setError(data.error);
      else {
        setAnalysis(data.analysis);
        setConversations(data.conversations);
        saveGroupAnalysis({
          conversationIds: ids,
          conversations: data.conversations,
          analysis: data.analysis,
        });
      }
    } catch (e) {
      setError(e instanceof Error ? e.message : "Analysis failed");
    } finally {
      setAnalyzing(false);
    }
  }, [ids]);

  const runCustom = useCallback(async () => {
    if (!customPrompt.trim()) return;
    setCustomAnalyzing(true);
    setError(null);
    try {
      const res = await fetch("/api/analyze-group/custom", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ conversationIds: ids, prompt: customPrompt }),
      });
      const data = await res.json();
      if (data.error) setError(data.error);
      else {
        saveGroupCustom(ids, { prompt: customPrompt, result: data.result });
      }
    } catch (e) {
      setError(e instanceof Error ? e.message : "Custom analysis failed");
    } finally {
      setCustomAnalyzing(false);
    }
  }, [ids, customPrompt]);

  const handleExportObsidian = () => {
    const stored = getStoredGroupAnalyses();
    const key = [...ids].sort().join(",");
    const existing = stored.find((a) => [...a.conversationIds].sort().join(",") === key);
    if (existing) {
      const uri = exportGroupToObsidian(existing);
      window.open(uri, "_blank");
      setExported(true);
      setTimeout(() => setExported(false), 2000);
    }
  };

  const sections = analysis
    ? [
        { icon: "🔗", title: "Cross-Conversation Themes", subtitle: "Recurring ideas and shared concerns", content: analysis.cross_conversation_themes },
        { icon: "⚡", title: "Contradictions & Tensions", subtitle: "Where conversations diverge or conflict", content: analysis.contradictions_and_tensions },
        { icon: "📈", title: "Evolution & Patterns", subtitle: "How ideas change over time", content: analysis.evolution_and_patterns },
        { icon: "🧩", title: "Synthesis", subtitle: "The bigger picture across all conversations", content: analysis.synthesis },
        { icon: "🚀", title: "Forward Thinking", subtitle: "Research directions from cross-conversation patterns", content: analysis.forward_thinking },
      ]
    : [];

  return (
    <main className="max-w-3xl mx-auto px-4 py-8">
      <Link href="/" className="text-slate-400 hover:text-white text-sm mb-6 inline-flex items-center gap-1">
        ← Back to conversations
      </Link>

      <header className="mb-6">
        <h1 className="text-2xl font-bold text-white mb-2">
          🧠 Group Analysis
        </h1>
        <p className="text-slate-400 text-sm">
          {ids.length} conversations selected for cross-conversation analysis
        </p>
        {conversations.length > 0 && (
          <div className="flex flex-wrap gap-2 mt-3">
            {conversations.map((c) => (
              <span key={c.id} className="text-xs bg-slate-800 text-slate-300 px-2 py-1 rounded-md">
                {c.emoji} {c.title}
              </span>
            ))}
          </div>
        )}
      </header>

      {error && (
        <div className="card p-6 border-red-500/50 mb-6">
          <p className="text-red-400">⚠ {error}</p>
        </div>
      )}

      {/* Analyze button */}
      {!analysis && !loading && (
        <button
          onClick={runAnalysis}
          disabled={analyzing}
          className="w-full card p-6 text-center hover:border-indigo-500/50 transition-colors cursor-pointer disabled:opacity-50 disabled:cursor-not-allowed mb-8"
        >
          {analyzing ? (
            <div className="flex items-center justify-center gap-3">
              <span className="pulse-dot text-2xl">⏳</span>
              <div>
                <p className="font-semibold text-white">Analyzing {ids.length} conversations...</p>
                <p className="text-slate-400 text-sm mt-1">Running cross-conversation analysis</p>
              </div>
            </div>
          ) : (
            <div>
              <p className="text-2xl mb-2">🧠</p>
              <p className="font-semibold text-white">Run Group Analysis</p>
              <p className="text-slate-400 text-sm mt-1">Find patterns across {ids.length} conversations</p>
            </div>
          )}
        </button>
      )}

      {/* Analysis results */}
      {sections.length > 0 && (
        <div className="mb-8">
          <div className="flex items-center justify-between mb-6">
            <h2 className="text-xl font-bold text-white flex items-center gap-2">
              🧠 Cross-Conversation Analysis
              <span className="text-xs bg-indigo-900/50 text-indigo-300 px-2 py-0.5 rounded-full font-normal">saved</span>
            </h2>
            <div className="flex items-center gap-2">
              <button
                onClick={handleExportObsidian}
                className="text-xs bg-purple-900/40 hover:bg-purple-800/50 text-purple-300 px-3 py-1.5 rounded-lg transition-colors"
              >
                {exported ? "✓ Saved" : "📓 Send to Obsidian"}
              </button>
              <button
                onClick={runAnalysis}
                disabled={analyzing}
                className="text-xs text-slate-500 hover:text-indigo-400 transition-colors px-2 py-1.5"
              >
                🔄 Re-analyze
              </button>
            </div>
          </div>
          <div className="space-y-6">
            {sections.map((section) => (
              <div key={section.title} className="card p-6">
                <div className="analysis-section">
                  <h3>{section.icon} {section.title}</h3>
                  <p className="text-xs text-slate-500 mb-3">{section.subtitle}</p>
                  <div className="whitespace-pre-wrap text-sm leading-relaxed">{section.content}</div>
                </div>
              </div>
            ))}
          </div>
        </div>
      )}

      {/* Custom group analysis */}
      <div className="mb-8">
        <button
          onClick={() => setShowCustom(!showCustom)}
          className="w-full card p-5 text-left hover:border-amber-500/50 transition-colors cursor-pointer flex items-center justify-between"
        >
          <div className="flex items-center gap-3">
            <span className="text-xl">⚙️</span>
            <div>
              <p className="font-semibold text-white">Custom Group Analysis</p>
              <p className="text-slate-500 text-sm">Ask a question across all selected conversations</p>
            </div>
          </div>
          <svg className={`w-5 h-5 text-slate-500 transition-transform ${showCustom ? "rotate-180" : ""}`} fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M19 9l-7 7-7-7" />
          </svg>
        </button>

        {showCustom && (
          <div className="card mt-2 p-6 border-amber-500/30">
            <textarea
              value={customPrompt}
              onChange={(e) => setCustomPrompt(e.target.value)}
              placeholder="e.g., How do different speakers frame land ownership? What shared assumptions about 'the good life' emerge across these conversations?"
              className="w-full bg-slate-900 border border-slate-700 rounded-lg p-3 text-sm text-slate-200 placeholder-slate-600 focus:border-amber-500 focus:outline-none resize-none mb-3"
              rows={3}
            />
            <div className="flex flex-wrap gap-2 mb-3">
              {[
                "How do speakers frame land ownership differently?",
                "What shared assumptions about 'the good life' emerge?",
                "Where does resistance to outside authority appear?",
                "What role does family legacy play across conversations?",
              ].map((p) => (
                <button key={p} onClick={() => setCustomPrompt(p)} className="text-xs bg-slate-800 hover:bg-slate-700 text-slate-400 hover:text-slate-200 px-2 py-1 rounded-md transition-colors">
                  {p}
                </button>
              ))}
            </div>
            <button
              onClick={runCustom}
              disabled={customAnalyzing || !customPrompt.trim()}
              className="bg-amber-600 hover:bg-amber-500 disabled:bg-slate-700 disabled:text-slate-500 text-white font-medium py-2 px-4 rounded-lg text-sm transition-colors"
            >
              {customAnalyzing ? "⏳ Analyzing..." : "Run Custom Group Analysis"}
            </button>
          </div>
        )}
      </div>
    </main>
  );
}

export default function GroupAnalysisPage() {
  return (
    <Suspense fallback={<div className="max-w-3xl mx-auto px-4 py-8"><div className="skeleton h-64 w-full" /></div>}>
      <GroupAnalysisContent />
    </Suspense>
  );
}
