import type { StoredAnalysis } from "./storage";
import type { StoredAdhdAnalysis, StoredRollup } from "./adhd-storage";

interface ObsidianExport {
  uri: string;
  filename: string;
  /** Some platforms refuse very long custom-scheme URIs; callers should
   *  fall back to downloadMarkdown when this is true. */
  uriTooLong: boolean;
}

// Windows caps ShellExecute URIs around 32KB; stay well under it.
const MAX_URI_LENGTH = 30_000;

function toISODate(value: string | undefined, fallback: string): string {
  if (value) {
    const d = new Date(value);
    if (!Number.isNaN(d.getTime())) return d.toISOString().split("T")[0];
  }
  const f = new Date(fallback);
  if (!Number.isNaN(f.getTime())) return f.toISOString().split("T")[0];
  return new Date().toISOString().split("T")[0];
}

function buildNoteContent(analysis: StoredAnalysis, date: string): string {
  let md = `---
title: "${(analysis.title || "Untitled").replace(/"/g, '\\"')}"
date: ${date}
analyzed: ${analysis.timestamp}
category: ${analysis.category || "conversation"}
source: Omi DK2
tags:
  - omi-analysis
  - fieldwork
  - pioneer-sovereignty
---

# ${analysis.title || "Untitled"}

> [!info] Analyzed on ${new Date(analysis.timestamp).toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" })} from an Omi DK2 conversation recorded ${date}.

## 📜 RQ1 — Documentary Record

${analysis.rq1_documentary_record}

## 🏚️ RQ2 — Everyday Practices

${analysis.rq2_everyday_practices}

## 🪶 RQ3 — CSKT Intersection

${analysis.rq3_cskt_intersection}

## 🐎 RQ4 — Wildness Imaginary

${analysis.rq4_wildness_imaginary}

## 🎯 Orienting Conditions

${analysis.conditions_check}

## ⚖️ Rival Hypothesis Test

${analysis.rival_hypothesis_test}

## ❌ Refutation Signals

${analysis.refutation_signals}

## 🚀 Forward Thinking

${analysis.forward_thinking}
`;

  if (analysis.custom) {
    md += `
## ⚙️ Custom Analysis

> **Prompt:** ${analysis.custom.prompt}

${analysis.custom.result}
`;
  }

  md += `
---
*Generated by [[Omi Thesis Analyzer]] — Pioneer Sovereignty fieldwork analysis.*
`;

  return md;
}

export function exportToObsidian(analysis: StoredAnalysis): ObsidianExport {
  const date = toISODate(analysis.date, analysis.timestamp);

  const safeName = (analysis.title || "Untitled")
    .replace(/[\/\\:*?"<>|]/g, "-")
    .substring(0, 80);

  const filename = `${date} - ${safeName}`;
  const content = buildNoteContent(analysis, date);

  const params = new URLSearchParams({
    vault: "PhDVault",
    name: `Fieldwork/Omi Analysis/${filename}`,
    content,
    append: "false",
  });

  const uri = `obsidian://advanced-uri?${params.toString()}`;
  return { uri, filename, uriTooLong: uri.length > MAX_URI_LENGTH };
}

export function downloadMarkdown(analysis: StoredAnalysis): void {
  const date = toISODate(analysis.date, analysis.timestamp);

  const safeName = (analysis.title || "Untitled")
    .replace(/[\/\\:*?"<>|]/g, "-")
    .substring(0, 80);

  const content = buildNoteContent(analysis, date);
  const blob = new Blob([content], { type: "text/markdown" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${date} - ${safeName}.md`;
  a.click();
  URL.revokeObjectURL(url);
}

// ── ADHD Aid export ──

function fmtCommitment(c: { direction: string; who: string; what: string; deadline: string; confidence: string; quote: string }, done: boolean): string {
  const box = done ? "✅" : "⬜";
  const dir = c.direction === "other_to_user" ? `${c.who} → me` : `me → ${c.who}`;
  return `- ${box} **${dir}** — ${c.what} (**${c.deadline}**, ${c.confidence})\n  > ${c.quote}`;
}

export function buildAdhdMarkdown(stored: StoredAdhdAnalysis): { markdown: string; filename: string } {
  const a = stored.analysis;
  const done = new Set(stored.doneKeys);
  const day = (stored.date || stored.timestamp).split("T")[0];
  const safeName = (stored.title || "Untitled").replace(/[\/\\:*?"<>|]/g, "-").substring(0, 80);

  const commitments = a.commitments.length
    ? a.commitments.map((c) => fmtCommitment(c, done.has(c.key))).join("\n")
    : "None.";
  const people = a.people.length
    ? a.people.map((p) => `### ${p.name} — ${p.relationship}\n- Shared: ${p.shared}\n- Tone: ${p.tone}\n- Owed: ${p.owed}`).join("\n\n")
    : "None.";
  const ahead = a.ahead.length
    ? a.ahead.map((x) => `- **${x.event}** (${x.date}) — prep: ${x.prep}; start: ${x.start_when}; conflict: ${x.conflict}`).join("\n")
    : "None.";
  const list = (items: string[]) => (items.length ? items.map((i) => `- ${i}`).join("\n") : "None.");

  const markdown = `---
title: "${(stored.title || "Untitled").replace(/"/g, '\\"')}"
date: ${day}
analyzed: ${stored.timestamp}
type: adhd-analysis
source: Omi DK2
tags:
  - omi-analysis
  - adhd-aid
---

# ${stored.title || "Untitled"} — ADHD Aid

> ${a.summary}

## ⚡ Do today

${list(a.do_today)}

## 📌 Commitments

${commitments}

## 🧠 Remember

${list(a.remember)}

## 👥 People

${people}

## 🔁 Open loops

${list(a.open_loops)}

## 📅 Ahead

${ahead}

---
*Generated by [[Omi Thesis Analyzer]] — ADHD Aid layer.*
`;
  return { markdown, filename: `ADHD - ${day} - ${safeName}` };
}

export function exportAdhdToObsidian(stored: StoredAdhdAnalysis): { uri: string; uriTooLong: boolean } {
  const { markdown, filename } = buildAdhdMarkdown(stored);
  const params = new URLSearchParams({
    vault: "PhDVault",
    name: `Fieldwork/Omi Analysis/${filename}`,
    content: markdown,
    append: "false",
  });
  const uri = `obsidian://advanced-uri?${params.toString()}`;
  return { uri, uriTooLong: uri.length > MAX_URI_LENGTH };
}

export function downloadAdhdMarkdown(stored: StoredAdhdAnalysis): void {
  const { markdown, filename } = buildAdhdMarkdown(stored);
  const blob = new Blob([markdown], { type: "text/markdown" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${filename}.md`;
  a.click();
  URL.revokeObjectURL(url);
}

